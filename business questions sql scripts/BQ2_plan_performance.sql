
/*
===============================================================================
PROJECT: MTN NIGERIA TARIFF ADJUSTMENT IMPACT ANALYSIS
BQ2: PLAN PERFORMANCE ANALYSIS
===============================================================================

BUSINESS QUESTION:
Which data plans experienced the largest changes in customer demand
following the tariff adjustment?

PURPOSE:
Compare plan-level transactions, customers, revenue, and ATV.
Export base metrics to Excel for change calculations and rankings.

METHODOLOGY:
1. Compare plan-level transaction volume, customer counts, and revenue before
   and after the tariff adjustment.
2. Calculate average daily transactions and average daily revenue to account
   for the unequal lengths of the two observation periods.
3. Calculate percentage changes between the two periods in Excel.
4. Classify plans to distinguish existing hiked plans, unchanged plans,
   new plans, discontinued plans, and the recalled Weekly 15GB Digital plan.

SQL DIALECT:
PostgreSQL

SQL FUNCTIONS USED:
Aggregate functions: COUNT(), SUM()
Distinct counting: COUNT(DISTINCT)
Numeric Formatting: ROUND()
Conditional logic: CASE
Joins: INNER JOIN
Grouping and Sorting: GROUP BY, ORDER BY
Aliasing: AS
Arithmetic Operators: /

KEY METRICS MEASURED:
1. Total Transactions per Plan: Total transactions recorded for each plan
   during each observation period.
2. Customers per Plan: Unique customers who purchased each plan during
   each observation period.
3. Total Revenue per Plan: Revenue generated by each plan during each
   observation period, expressed in NGN.
4. Average Daily Transactions: Transactions per plan divided by the number
   of calendar days in the relevant observation period.
5. Average Daily Revenue: Revenue per plan divided by the number of calendar
   days in the relevant observation period, expressed in NGN.
6. Daily Demand Change (%): Percentage change in average daily transactions
   between the pre-hike and post-hike periods.
7. Daily Revenue Change (%): Percentage change in average daily revenue
   between the pre-hike and post-hike periods.
8. Customer Change (%): Percentage change in the number of unique customers
   purchasing each plan between the two periods, interpreted with caution
   because the observation periods have different lengths.
9. Transaction Change (%): Percentage change in total transactions between
   the two periods, interpreted with caution because the observation periods
   have different lengths.
10. Total Revenue Change (%): Percentage change in total revenue between
    the two periods, interpreted with caution because the observation periods
    have different lengths.

LIMITATIONS:
- The periods have different durations.
- New and discontinued plans have limited comparability.
- Weekly 15GB Digital was recalled after two post-hike days.
- Before-and-after comparisons do not establish causation.
===============================================================================
*/

-- STEP 1: Aggregate transaction, customer, revenue, and ATV metrics.
WITH plan_metrics AS (
    SELECT
        ft.plan_id,

        COUNT(ft.transaction_id)
            FILTER (WHERE dd.hike_period_label = 'Pre-Hike')
            AS pre_transactions,

        COUNT(ft.transaction_id)
            FILTER (WHERE dd.hike_period_label = 'Post-Hike')
            AS post_transactions,

        COUNT(DISTINCT ft.customer_id)
            FILTER (WHERE dd.hike_period_label = 'Pre-Hike')
            AS pre_customers,

        COUNT(DISTINCT ft.customer_id)
            FILTER (WHERE dd.hike_period_label = 'Post-Hike')
            AS post_customers,

        SUM(ft.amount_ngn)
            FILTER (WHERE dd.hike_period_label = 'Pre-Hike')
            AS pre_revenue,

        SUM(ft.amount_ngn)
            FILTER (WHERE dd.hike_period_label = 'Post-Hike')
            AS post_revenue,

        AVG(ft.amount_ngn)
            FILTER (WHERE dd.hike_period_label = 'Pre-Hike')
            AS pre_atv,

        AVG(ft.amount_ngn)
            FILTER (WHERE dd.hike_period_label = 'Post-Hike')
            AS post_atv

    FROM fact_transactions AS ft
    INNER JOIN dim_date AS dd
        ON ft.transaction_date = dd.full_date

    WHERE dd.full_date BETWEEN DATE '2024-12-01'
                           AND DATE '2025-04-30'

    GROUP BY ft.plan_id
),

-- STEP 2: Calculate average daily active customers, including zero-activity days.
daily_customers AS (
    SELECT
        dp.plan_id,
        dd.hike_period_label,
        dd.full_date,
        COUNT(DISTINCT ft.customer_id) AS active_customers

    FROM dim_plans AS dp
    CROSS JOIN dim_date AS dd

    LEFT JOIN fact_transactions AS ft
        ON ft.plan_id = dp.plan_id
        AND ft.transaction_date = dd.full_date

    WHERE dd.full_date BETWEEN DATE '2024-12-01'
                           AND DATE '2025-04-30'

    GROUP BY
        dp.plan_id,
        dd.hike_period_label,
        dd.full_date
),

daily_customer_averages AS (
    SELECT
        plan_id,

        AVG(active_customers)
            FILTER (WHERE hike_period_label = 'Pre-Hike')
            AS pre_avg_daily_customers,

        AVG(active_customers)
            FILTER (WHERE hike_period_label = 'Post-Hike')
            AS post_avg_daily_customers

    FROM daily_customers
    GROUP BY plan_id
)

-- STEP 3: Combine plan details with the metrics needed for Excel.

-- STEP 3: Return base metrics for the Excel stakeholder analysis.
SELECT
    dp.plan_name,

    CASE
        WHEN dp.price_pre IS NULL THEN 'New Plan'
        WHEN dp.price_post IS NULL THEN 'Discontinued Plan'
        WHEN LOWER(dp.plan_status) = 'hiked_rolled_back'
            THEN 'Rolled-Back Plan'
        WHEN dp.price_post > dp.price_pre THEN 'Existing Hiked Plan'
        WHEN dp.plan_name = 'Monthly 40GB'
            THEN 'Unchanged Price - Reduced Allowance'
        ELSE 'Unchanged Plan'
    END AS plan_category,

    COALESCE(pm.pre_transactions, 0) AS pre_transactions,
    COALESCE(pm.post_transactions, 0) AS post_transactions,

    COALESCE(pm.pre_customers, 0) AS pre_customers,
    COALESCE(pm.post_customers, 0) AS post_customers,

    COALESCE(pm.pre_revenue, 0) AS pre_revenue,
    COALESCE(pm.post_revenue, 0) AS post_revenue

FROM dim_plans AS dp

LEFT JOIN plan_metrics AS pm
    ON dp.plan_id = pm.plan_id

ORDER BY dp.plan_name;
